  function escapeHtml(str) {
    return String(str || '')
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#039;');
  }

  let toastTimer = null;
  function showToast(message) {
    let toastEl = document.getElementById('site-toast');
    if (!toastEl) {
      toastEl = document.createElement('div');
      toastEl.id = 'site-toast';
      toastEl.className = 'toast-notification';
      toastEl.setAttribute('role', 'status');
      toastEl.setAttribute('aria-live', 'polite');
      document.body.appendChild(toastEl);
    }
    toastEl.textContent = message;
    toastEl.classList.add('is-visible');
    if (toastTimer) clearTimeout(toastTimer);
    toastTimer = setTimeout(function () {
      toastEl.classList.remove('is-visible');
    }, 3200);
  }

  function getStoredProjects() {
    try {
      const raw = localStorage.getItem(STORAGE_KEYS.PROJECTS);
      if (!raw) return DEFAULT_PROJECTS.slice();
      const parsed = JSON.parse(raw);
      return Array.isArray(parsed) && parsed.length > 0 ? parsed : DEFAULT_PROJECTS.slice();
    } catch (_err) {
      return DEFAULT_PROJECTS.slice();
    }
  }

  function saveStoredProjects(projects) {
    try {
      localStorage.setItem(STORAGE_KEYS.PROJECTS, JSON.stringify(projects));
    } catch (_err) {
      showToast('Browser storage quota reached.');
    }
  }

  /* --------------------------------------------------------------------------
   * 3. THEME MANAGEMENT (LIGHT / DARK)
   * -------------------------------------------------------------------------- */
  function initTheme() {
    let savedTheme = null;
    try {
      savedTheme = localStorage.getItem(STORAGE_KEYS.THEME);
    } catch (_e) {
      savedTheme = null;
    }

    const prefersDark = window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches;
    const activeTheme = savedTheme || (prefersDark ? 'dark' : 'light');
    applyTheme(activeTheme);

    const toggleButtons = document.querySelectorAll('[data-action="toggle-theme"]');
    toggleButtons.forEach(function (btn) {
      btn.addEventListener('click', function () {
        const current = document.documentElement.getAttribute('data-theme') === 'dark' ? 'dark' : 'light';
        const next = current === 'dark' ? 'light' : 'dark';
        applyTheme(next);
        try {
          localStorage.setItem(STORAGE_KEYS.THEME, next);
        } catch (_e) {
          /* ignore private browsing restriction */
        }
        showToast(next === 'dark' ? 'Dark editorial theme enabled' : 'Light architectural theme enabled');
      });
    });
  }

  function applyTheme(theme) {
    if (theme === 'dark') {
      document.documentElement.setAttribute('data-theme', 'dark');
    } else {
      document.documentElement.removeAttribute('data-theme');
    }

    const toggleButtons = document.querySelectorAll('[data-action="toggle-theme"]');
    toggleButtons.forEach(function (btn) {
      const label = theme === 'dark' ? 'Switch to light theme' : 'Switch to dark theme';
      btn.setAttribute('aria-label', label);
      btn.setAttribute('title', label);
      const iconSpan = btn.querySelector('[data-theme-icon]');
      if (iconSpan) {
        iconSpan.textContent = theme === 'dark' ? '☀' : '☾';
      }
    });
  }

