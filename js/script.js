  /* --------------------------------------------------------------------------
   * 7. CONTACT PAGE: VALIDATION, COPY EMAIL & LOCALSTORAGE INBOX
   * -------------------------------------------------------------------------- */
  function initContactPage() {
    const copyEmailBtns = document.querySelectorAll('[data-copy-email]');
    copyEmailBtns.forEach(function (btn) {
      btn.addEventListener('click', function () {
        const email = btn.getAttribute('data-copy-email') || 'julian.vance@architect.dev';
        if (navigator.clipboard && navigator.clipboard.writeText) {
          navigator.clipboard.writeText(email).then(function () {
            showToast('Copied ' + email + ' to clipboard');
          });
        } else {
          showToast('Email address: ' + email);
        }
      });
    });

    const form = document.getElementById('contact-inquiry-form');
    const inboxContainer = document.getElementById('local-inquiries-list');
    const inboxCountEl = document.getElementById('inquiries-count-badge');
    const exportJsonBtn = document.getElementById('export-inquiries-json');
    const clearInquiriesBtn = document.getElementById('clear-all-inquiries');
    const successBanner = document.getElementById('contact-success-banner');

    function getInquiries() {
      try {
        const raw = localStorage.getItem(STORAGE_KEYS.INQUIRIES);
        if (!raw) return [];
        const parsed = JSON.parse(raw);
        return Array.isArray(parsed) ? parsed : [];
      } catch (_e) {
        return [];
      }
    }

    function saveInquiries(list) {
      try {
        localStorage.setItem(STORAGE_KEYS.INQUIRIES, JSON.stringify(list));
      } catch (_e) {
        showToast('Unable to save inquiry in private browsing mode.');
      }
    }

    function renderInquiries() {
      if (!inboxContainer) return;
      const list = getInquiries();
      if (inboxCountEl) {
        inboxCountEl.textContent = list.length + (list.length === 1 ? ' saved inquiry' : ' saved inquiries');
      }

      if (list.length === 0) {
        inboxContainer.innerHTML =
          '<div class="inbox-item" style="text-align:center; padding: 32px;">' +
          '<p class="body-md" style="margin: 0 auto;">No local inquiries stored yet. Submit the form above to test browser-side persistence and mailto dispatch.</p>' +
          '</div>';
        return;
      }

      inboxContainer.innerHTML = list
        .map(function (item) {
          const mailtoHref =
            'mailto:julian.vance@architect.dev?subject=' +
            encodeURIComponent('[Portfolio Inquiry] ' + item.scope + ' — ' + item.name) +
            '&body=' +
            encodeURIComponent(
              'Name: ' +
                item.name +
                '\nEmail: ' +
                item.email +
                '\nScope: ' +
                item.scope +
                '\nTimeline / Budget: ' +
                item.budget +
                '\n\nMessage:\n' +
                item.message
            );

          return (
            '<article class="inbox-item">' +
            '<div class="inbox-item-header">' +
            '<div>' +
            '<strong style="font-size: 1rem;">' +
            escapeHtml(item.name) +
            '</strong>' +
            '<span class="meta-inline" style="display:inline-flex; margin-left: 10px;">' +
            '<span>' +
            escapeHtml(item.email) +
            '</span>' +
            '<span class="meta-sep">·</span>' +
            '<span>' +
            escapeHtml(item.scope) +
            '</span>' +
            '<span class="meta-sep">·</span>' +
            '<span class="tabular-nums">' +
            escapeHtml(item.budget) +
            '</span>' +
            '</span>' +
            '</div>' +
            '<span class="meta-inline tabular-nums">' +
            escapeHtml(item.timestamp) +
            '</span>' +
            '</div>' +
            '<p class="body-md">' +
            escapeHtml(item.message) +
            '</p>' +
            '<div style="display:flex; flex-wrap:wrap; align-items:center; gap: 16px; padding-top: 8px;">' +
            '<a href="' +
            mailtoHref +
            '" class="text-action-link">Launch in Email Client (mailto:) →</a>' +
            '<button type="button" class="text-action-link" style="color: var(--status-error);" data-delete-inquiry="' +
            escapeHtml(item.id) +
            '">Delete Record</button>' +
            '</div>' +
            '</article>'
          );
        })
        .join('');

      inboxContainer.querySelectorAll('[data-delete-inquiry]').forEach(function (btn) {
        btn.addEventListener('click', function () {
          const id = btn.getAttribute('data-delete-inquiry');
          const updated = getInquiries().filter(function (i) {
            return i.id !== id;
          });
          saveInquiries(updated);
          renderInquiries();
          showToast('Inquiry deleted from LocalStorage');
        });
      });
    }

    if (form) {
      form.addEventListener('submit', function (e) {
        e.preventDefault();
        const nameInput = document.getElementById('contact-name');
        const emailInput = document.getElementById('contact-email');
        const scopeInput = document.getElementById('contact-scope');
        const budgetInput = document.getElementById('contact-budget');
        const messageInput = document.getElementById('contact-message');

        let isValid = true;
        function setFieldState(inputEl, errorId, condition) {
          const errEl = document.getElementById(errorId);
          if (!condition) {
            isValid = false;
            if (inputEl) inputEl.classList.add('has-error');
            if (errEl) errEl.classList.add('is-visible');
          } else {
            if (inputEl) inputEl.classList.remove('has-error');
            if (errEl) errEl.classList.remove('is-visible');
          }
        }

        const nameVal = nameInput ? nameInput.value.trim() : '';
        const emailVal = emailInput ? emailInput.value.trim() : '';
        const messageVal = messageInput ? messageInput.value.trim() : '';
        const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

        setFieldState(nameInput, 'error-contact-name', nameVal.length >= 2);
        setFieldState(emailInput, 'error-contact-email', emailRegex.test(emailVal));
        setFieldState(messageInput, 'error-contact-message', messageVal.length >= 15);

        if (!isValid) {
          showToast('Please check the highlighted form fields.');
          return;
        }

        const newInquiry = {
          id: 'inq-' + Date.now(),
          name: nameVal,
          email: emailVal,
          scope: scopeInput ? scopeInput.value : 'Systems Architecture',
          budget: budgetInput ? budgetInput.value : '$15k – $30k',
          message: messageVal,
          timestamp: new Date().toISOString().slice(0, 16).replace('T', ' ') + ' UTC'
        };

        const list = getInquiries();
        list.unshift(newInquiry);
        saveInquiries(list);
        form.reset();

        if (successBanner) {
          successBanner.classList.add('is-success');
          successBanner.textContent =
            'Inquiry validated and saved to your browser LocalStorage inbox below. You can also dispatch it directly via your email client.';
        }
        renderInquiries();
        showToast('Inquiry saved to LocalStorage inbox!');
      });
    }

    if (exportJsonBtn) {
      exportJsonBtn.addEventListener('click', function () {
        const list = getInquiries();
        if (list.length === 0) {
          showToast('No saved inquiries to export.');
          return;
        }
        const blob = new Blob([JSON.stringify(list, null, 2)], { type: 'application/json' });
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = 'portfolio-inquiries-export.json';
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        URL.revokeObjectURL(url);
        showToast('Exported ' + list.length + ' inquiries as JSON');
      });
    }

    if (clearInquiriesBtn) {
      clearInquiriesBtn.addEventListener('click', function () {
        localStorage.removeItem(STORAGE_KEYS.INQUIRIES);
        renderInquiries();
        if (successBanner) successBanner.classList.remove('is-success');
        showToast('Cleared all saved inquiries from LocalStorage');
      });
    }

    renderInquiries();
  }

